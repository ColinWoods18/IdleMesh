"""Offline evaluation of the availability predictor (S6.2): Brier score, skill and calibration.

    python experiments/analysis/predictor_eval.py --synthetic            # a synthetic fleet (no real data needed)
    python experiments/analysis/predictor_eval.py --db coordinator.sqlite3 --test-days 7

With `--db` the database is copied first and only the copy is read. The model is fitted on the
`--train-days` before the split and scored on the `--test-days` after it; by default the split is
`--test-days` before the newest sample. Writes `results/predictor-eval-<label>.md` and `.json` beside this file
unless `--no-write`. The notebook `predictor-evaluation.ipynb` calls `run()` and draws the calibration curve.
"""
import argparse
import json
import sqlite3
import sys
import tempfile
from contextlib import closing
from datetime import datetime, timedelta, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "coordinator"))

from idlemesh_coord.predictor import PredictorPolicy, evaluate, synthetic  # noqa: E402
from idlemesh_coord.store import Store, parse  # noqa: E402

RESULTS = Path(__file__).resolve().parent / "results"
SYNTHETIC_FLEET = {"n_office_1": "office", "n_office_2": "office", "n_office_3": "office", "n_lab_1": "lab",
                   "n_lab_2": "lab", "n_server": "server", "n_laptop_1": "laptop", "n_laptop_2": "laptop"}
SYNTHETIC_START = datetime(2026, 9, 7, tzinfo=timezone.utc)  # a Monday


def _copy(db: Path, into: Path) -> Path:
    out = into / "copy.sqlite3"
    with closing(sqlite3.connect(f"file:{db}?mode=ro", uri=True)) as src, closing(sqlite3.connect(out)) as dst:
        src.backup(dst)
    return out


def run(db: Path | None = None, train_days: float = 28, test_days: float = 7, horizons=(30, 60, 120),
        prior_strength: float = 10.0, seed: int = 1, utc: bool = False) -> dict:
    """Evaluate on a copy of `db`, or on a synthetic fleet when `db` is None. Returns one result per horizon."""
    tz = timezone.utc if utc or db is None else None  # synthetic routines are written in UTC
    with tempfile.TemporaryDirectory() as tmp:
        if db is None:
            store = Store(str(Path(tmp) / "synthetic.sqlite3"))
            synthetic.fleet(store, SYNTHETIC_START, int(train_days + test_days), SYNTHETIC_FLEET, seed, tz)
            label = f"synthetic-seed{seed}"
        else:
            store = Store(str(_copy(db, Path(tmp))))
            label = db.stem
        nodes = [r["node"] for r in store.all("SELECT DISTINCT node FROM idle_samples ORDER BY node")]
        newest = store.one("SELECT MAX(ts) AS t FROM idle_samples")["t"]
        if not nodes or not newest:
            raise SystemExit("no idle samples to evaluate")
        end = parse(newest) + timedelta(seconds=1)
        split = end - timedelta(days=test_days)
        policy = PredictorPolicy(window_days=train_days, horizons_min=tuple(horizons), default_horizon_min=horizons[0],
                                 prior_strength=prior_strength)
        results = [evaluate(store, nodes, policy, split, end, h, tz) for h in horizons]
        store.close()  # before the temporary directory goes (Windows cannot delete an open file)
    return {"label": label, "nodes": len(nodes), "train_days": train_days, "test_days": test_days,
            "prior_strength": prior_strength, "time_zone": "UTC" if tz else "coordinator local",
            "generated": datetime.now(timezone.utc).isoformat(timespec="seconds"), "results": results}


def markdown(report: dict) -> str:
    lines = [f"# Availability predictor evaluation: {report['label']}", "",
             f"Generated by `experiments/analysis/predictor_eval.py` at {report['generated']}. "
             f"{report['nodes']} nodes; fitted on {report['train_days']:g} days, scored on the next "
             f"{report['test_days']:g}; prior strength {report['prior_strength']:g}; hours of the week in "
             f"{report['time_zone']} time.", "",
             "Brier: 0 is perfect, 0.25 is a constant 0.5. Skill = 1 - Brier / Brier(baseline): above 0 means the "
             "hour-of-week model beats the baseline. Fleet rate: one figure for every node and hour. Node rate: "
             "each node's own figure, ignoring the hour.", "",
             "| Horizon | Scored | Stayed idle | Mean prediction | Brier | Brier, fleet rate | Brier, node rate |"
             " Skill vs. fleet | Skill vs. node |",
             "|---|---|---|---|---|---|---|---|---|"]
    for r in report["results"]:
        lines.append(f"| {r['horizon_min']} min | {r['n']} | {r['observed_rate']:.3f} | {r['mean_p']:.3f} |"
                     f" {r['brier']:.4f} | {r['brier_fleet_rate']:.4f} | {r['brier_node_rate']:.4f} |"
                     f" {r['skill_vs_fleet']:.3f} | {r['skill_vs_node']:.3f} |")
    first = report["results"][1 if len(report["results"]) > 1 else 0]
    lines += ["", f"## Calibration, {first['horizon_min']} min", "",
              "| Predicted | Samples | Mean prediction | Observed |", "|---|---|---|---|"]
    lines += [f"| {b['bin'][0]:.1f}-{b['bin'][1]:.1f} | {b['n']} | {b['mean_p']:.3f} | {b['observed']:.3f} |"
              for b in first["calibration"]]
    lines += ["", f"## By node, {first['horizon_min']} min", "",
              "| Node | Scored | Stayed idle | Brier | Skill vs. node |", "|---|---|---|---|---|"]
    for node, s in sorted(first["nodes"].items()):
        if s.get("n"):
            lines.append(f"| {node} | {s['n']} | {s['observed_rate']:.3f} | {s['brier']:.4f} |"
                         f" {s['skill_vs_node']:.3f} |" if s["skill_vs_node"] is not None else
                         f"| {node} | {s['n']} | {s['observed_rate']:.3f} | {s['brier']:.4f} | - |")
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    src = ap.add_mutually_exclusive_group(required=True)
    src.add_argument("--db", type=Path, help="a coordinator database (copied, never changed)")
    src.add_argument("--synthetic", action="store_true", help="evaluate on a synthetic fleet")
    ap.add_argument("--train-days", type=float, default=28)
    ap.add_argument("--test-days", type=float, default=7)
    ap.add_argument("--prior-strength", type=float, default=10.0)
    ap.add_argument("--seed", type=int, default=1, help="synthetic fleet seed")
    ap.add_argument("--utc", action="store_true", help="hours of the week in UTC rather than local time")
    ap.add_argument("--no-write", action="store_true")
    a = ap.parse_args(argv)
    report = run(a.db, a.train_days, a.test_days, prior_strength=a.prior_strength, seed=a.seed, utc=a.utc)
    text = markdown(report)
    if not a.no_write:
        RESULTS.mkdir(exist_ok=True)
        (RESULTS / f"predictor-eval-{report['label']}.md").write_text(text, encoding="utf-8", newline="\n")
        (RESULTS / f"predictor-eval-{report['label']}.json").write_text(json.dumps(report, indent=2) + "\n",
                                                                         encoding="utf-8", newline="\n")
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
